import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const [videoId, languageCode = 'en', fromValue = '330000', toValue = '380000'] =
  process.argv.slice(2);
const excerptStartMs = Number(fromValue);
const excerptEndMs = Number(toValue);

if (
  !videoId ||
  !/^[A-Za-z0-9_-]{11}$/u.test(videoId) ||
  !/^[A-Za-z0-9-]{2,16}$/u.test(languageCode) ||
  !Number.isFinite(excerptStartMs) ||
  !Number.isFinite(excerptEndMs) ||
  excerptStartMs < 0 ||
  excerptEndMs <= excerptStartMs
) {
  throw new Error(
    '用法：npm run fixture:youtube -- <video-id> [language] [from-ms] [to-ms]。时间范围必须是递增的非负毫秒值。',
  );
}

const watchResponse = await fetch(`https://www.youtube.com/watch?v=${videoId}`);
if (!watchResponse.ok) {
  throw new Error(`无法读取 YouTube 视频页面（HTTP ${watchResponse.status}）：${videoId}`);
}
const watchHtml = await watchResponse.text();
const apiKey = watchHtml.match(/"INNERTUBE_API_KEY":"([^"]+)"/u)?.[1];
if (!apiKey) {
  throw new Error(`视频页面没有公开 Innertube API Key：${videoId}`);
}

const playerResponse = await fetch(
  `https://www.youtube.com/youtubei/v1/player?key=${encodeURIComponent(apiKey)}`,
  {
    method: 'POST',
    headers: { 'Content-Type': 'application/json' },
    body: JSON.stringify({
      context: {
        client: {
          clientName: 'ANDROID',
          clientVersion: '20.10.38',
          hl: 'en',
          gl: 'US',
        },
      },
      videoId,
      contentCheckOk: true,
      racyCheckOk: true,
    }),
  },
);
if (!playerResponse.ok) {
  throw new Error(`YouTube 播放器接口请求失败（HTTP ${playerResponse.status}）：${videoId}`);
}

const playerPayload = await playerResponse.json();
const tracks = playerPayload?.captions?.playerCaptionsTracklistRenderer?.captionTracks ?? [];
const matchingTracks = tracks.filter((track) => track.languageCode === languageCode);
const track = matchingTracks.find((candidate) => candidate.kind !== 'asr') ?? matchingTracks[0];
if (!track?.baseUrl) {
  const availableLanguages = tracks
    .map((candidate) => candidate.languageCode)
    .filter(Boolean)
    .join(', ');
  throw new Error(
    `视频 ${videoId} 没有 ${languageCode} 字幕轨。可用语言：${availableLanguages || '无'}。`,
  );
}

const captionUrl = new URL(track.baseUrl);
captionUrl.searchParams.set('fmt', 'json3');
const captionResponse = await fetch(captionUrl);
if (!captionResponse.ok) {
  throw new Error(
    `YouTube JSON3 字幕请求失败（HTTP ${captionResponse.status}）：${videoId}/${languageCode}`,
  );
}
const captionText = await captionResponse.text();
if (!captionText.trim()) {
  throw new Error(`YouTube 返回了空字幕数据：${videoId}/${languageCode}`);
}
const captionPayload = JSON.parse(captionText);
const events = Array.isArray(captionPayload.events) ? captionPayload.events : [];
if (events.length === 0) {
  throw new Error(`YouTube JSON3 字幕没有事件：${videoId}/${languageCode}`);
}

const fixture = {
  videoId,
  languageCode,
  isAutoGenerated: track.kind === 'asr',
  events,
};
const excerpt = {
  ...fixture,
  excerptStartMs,
  excerptEndMs,
  events: events.filter(
    (event) =>
      typeof event.tStartMs === 'number' &&
      event.tStartMs >= excerptStartMs &&
      event.tStartMs <= excerptEndMs,
  ),
};

const localDirectory = path.resolve('.fixtures/youtube');
const testDirectory = path.resolve('test/fixtures/youtube');
await Promise.all([
  mkdir(localDirectory, { recursive: true }),
  mkdir(testDirectory, { recursive: true }),
]);

const fullPath = path.join(localDirectory, `${videoId}.${languageCode}.full.json`);
const excerptPath = path.join(
  testDirectory,
  `${videoId}.${languageCode}.${excerptStartMs}-${excerptEndMs}.json`,
);
await Promise.all([
  writeFile(fullPath, `${JSON.stringify(fixture, null, 2)}\n`, 'utf8'),
  writeFile(excerptPath, `${JSON.stringify(excerpt, null, 2)}\n`, 'utf8'),
]);

console.error(`完整字幕：${fullPath}`);
console.error(`测试片段：${excerptPath}`);
console.error(`字幕事件：完整 ${events.length}，片段 ${excerpt.events.length}`);
